CREATE TABLE cecamed.doctors (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL UNIQUE REFERENCES cecamed.user_accounts(id),
 full_name VARCHAR(150) NOT NULL,
 specialty VARCHAR(150) NOT NULL,
 active BOOLEAN NOT NULL DEFAULT TRUE,
 version BIGINT NOT NULL DEFAULT 0
);
CREATE TABLE cecamed.doctor_availability (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 doctor_id BIGINT NOT NULL REFERENCES cecamed.doctors(id),
 day_of_week VARCHAR(10) NOT NULL CHECK (day_of_week IN ('MONDAY','TUESDAY','WEDNESDAY','THURSDAY','FRIDAY','SATURDAY','SUNDAY')),
 start_time TIME NOT NULL,
 end_time TIME NOT NULL,
 slot_duration_minutes INT NOT NULL CHECK (slot_duration_minutes BETWEEN 5 AND 240),
 CONSTRAINT ck_doctor_hours CHECK (start_time < end_time)
);
CREATE TABLE cecamed.appointments (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 doctor_id BIGINT NOT NULL REFERENCES cecamed.doctors(id),
 patient_id BIGINT NOT NULL REFERENCES cecamed.patients(id),
 start_time TIMESTAMP WITH TIME ZONE NOT NULL,
 end_time TIMESTAMP WITH TIME ZONE NOT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE' CHECK (status IN ('PENDIENTE','CONFIRMADA','EN_SALA','ATENDIDA','CANCELADA','NO_ASISTIO')),
 reason_for_visit VARCHAR(2000) NOT NULL,
 cancellation_reason VARCHAR(500),
 notes VARCHAR(2000),
 checked_in_at TIMESTAMP WITH TIME ZONE,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL,
 updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
 version BIGINT NOT NULL DEFAULT 0,
 CONSTRAINT ck_appointment_interval CHECK (start_time < end_time)
);
CREATE INDEX idx_appointments_doctor_date ON cecamed.appointments(doctor_id,start_time);
CREATE INDEX idx_appointments_patient_date ON cecamed.appointments(patient_id,start_time);
CREATE TABLE cecamed.schedule_blocks (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 doctor_id BIGINT NOT NULL REFERENCES cecamed.doctors(id),
 title VARCHAR(150) NOT NULL,
 start_date_time TIMESTAMP WITH TIME ZONE NOT NULL,
 end_date_time TIMESTAMP WITH TIME ZONE NOT NULL,
 block_type VARCHAR(30) NOT NULL,
 all_day BOOLEAN NOT NULL DEFAULT FALSE,
 reason VARCHAR(500),
 created_at TIMESTAMP WITH TIME ZONE NOT NULL,
 CONSTRAINT ck_block_interval CHECK (start_date_time < end_date_time)
);
CREATE INDEX idx_schedule_blocks_doctor ON cecamed.schedule_blocks(doctor_id,start_date_time);
CREATE TABLE cecamed.patient_portal_accounts (
 user_id BIGINT PRIMARY KEY REFERENCES cecamed.user_accounts(id),
 patient_id BIGINT NOT NULL UNIQUE REFERENCES cecamed.patients(id)
);
CREATE TABLE cecamed.appointment_audit (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 appointment_id BIGINT NOT NULL REFERENCES cecamed.appointments(id),
 action VARCHAR(30) NOT NULL,
 actor VARCHAR(80) NOT NULL,
 details VARCHAR(1000),
 occurred_at TIMESTAMP WITH TIME ZONE NOT NULL
);
