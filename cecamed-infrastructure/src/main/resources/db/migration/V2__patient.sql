CREATE TABLE cecamed.patients (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    identification_number VARCHAR(50) NOT NULL,
    first_name VARCHAR(150) NOT NULL,
    last_name VARCHAR(150) NOT NULL,
    full_name VARCHAR(300) NOT NULL,
    birth_date DATE NOT NULL,
    gender VARCHAR(20) NOT NULL CHECK (gender IN ('MASCULINO', 'FEMENINO')),
    blood_type VARCHAR(20) NOT NULL CHECK (blood_type IN ('A_POSITIVO', 'A_NEGATIVO', 'B_POSITIVO', 'B_NEGATIVO', 'AB_POSITIVO', 'AB_NEGATIVO', 'O_POSITIVO', 'O_NEGATIVO', 'DESCONOCIDO')),
    phone VARCHAR(50),
    email VARCHAR(150),
    address VARCHAR(255),
    emergency_contact_name VARCHAR(150),
    emergency_contact_phone VARCHAR(50),
    emergency_contact_relationship VARCHAR(50),
    notes VARCHAR(500),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    medical_record_number VARCHAR(50),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uq_patients_identification_number UNIQUE (identification_number)
);

CREATE INDEX idx_patients_lower_first_name ON cecamed.patients (lower(first_name));
CREATE INDEX idx_patients_lower_last_name ON cecamed.patients (lower(last_name));
CREATE INDEX idx_patients_active ON cecamed.patients (active);
CREATE INDEX idx_patients_birth_date ON cecamed.patients (birth_date);