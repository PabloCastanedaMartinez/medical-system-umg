ALTER TABLE cecamed.patients ALTER COLUMN identification_number DROP NOT NULL;
ALTER TABLE cecamed.consultations ALTER COLUMN consultation_id ADD GENERATED BY DEFAULT AS IDENTITY;
SELECT setval(pg_get_serial_sequence('cecamed.consultations', 'consultation_id'),
    COALESCE((SELECT MAX(consultation_id) FROM cecamed.consultations), 0) + 1, false);
UPDATE cecamed.patients p SET medical_record_number = COALESCE(
    (SELECT record_number FROM cecamed.medical_records r WHERE r.patient_id=p.id), 'EXP-' || p.id)
WHERE medical_record_number IS NULL;
INSERT INTO cecamed.medical_records (patient_id, record_number, created_at, updated_at)
SELECT id, COALESCE(medical_record_number, 'EXP-' || id), created_at, updated_at
FROM cecamed.patients p WHERE NOT EXISTS (SELECT 1 FROM cecamed.medical_records r WHERE r.patient_id=p.id);
ALTER TABLE cecamed.consultations ADD COLUMN icd10_code VARCHAR(20);
