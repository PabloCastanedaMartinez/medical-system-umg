CREATE TABLE cecamed.patient_documents (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 patient_id BIGINT NOT NULL REFERENCES cecamed.patients(id),
 storage_key VARCHAR(36) NOT NULL UNIQUE,
 original_file_name VARCHAR(255) NOT NULL,
 file_type VARCHAR(100) NOT NULL CHECK (file_type IN ('application/pdf', 'image/png', 'image/jpeg')),
 document_type VARCHAR(40) NOT NULL CHECK (document_type IN ('ESTUDIO_LABORATORIO', 'IMAGEN_RAYOS_X', 'RECETA_MEDICA', 'INFORME_EXTERNO', 'CONSENTIMIENTO_INFORMADO', 'OTRO')),
 file_size_bytes BIGINT NOT NULL CHECK (file_size_bytes BETWEEN 1 AND 15728640),
 checksum_sha256 VARCHAR(64) NOT NULL,
 description VARCHAR(2000),
 created_at TIMESTAMP WITH TIME ZONE NOT NULL,
 updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
 active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE INDEX ix_patient_documents_patient ON cecamed.patient_documents(patient_id, active, created_at DESC);
